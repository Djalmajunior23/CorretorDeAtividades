  static calculateItemTriMetrics(params: {
    itemId: string;
    itemTitle: string;
    submissions: ItemSubmissionStat[];
  }): ItemTriMetrics {
    const subs = params.submissions || [];
    const totalAttempts = subs.length;

    if (totalAttempts === 0) {
      return {
        itemId: params.itemId,
        itemTitle: params.itemTitle,
        difficultyParamB: 0.0,
        discriminationParamA: 1.0,
        guessingParamC: 0.2,
        successRatePercentage: 50,
        pointBiserialCorrelation: 0.4,
        totalAttempts: 0,
        qualityStatus: "ADEQUADO",
        diagnosticRecommendation: "Item sem submissões registradas. Aguardando calibração empírica."
      };
    }

    const correctCount = subs.filter(s => s.isCorrect).length;
    const successRate = (correctCount / totalAttempts) * 100;

    // Parâmetro b (Dificuldade): b = -ln(p / (1 - p)) mapeado entre -3.0 e +3.0
    const p = Math.max(0.01, Math.min(0.99, correctCount / totalAttempts));
    let paramB = -Math.log(p / (1 - p));
    paramB = Math.round(Math.max(-3.0, Math.min(3.0, paramB)) * 100) / 100;

    // Correlação Ponto Bisserial (r_pbi) entre acerto no item e habilidade geral do aluno
    const avgScoreTotal = subs.reduce((acc, s) => acc + s.studentAbilityScore, 0) / totalAttempts;
    const correctSubs = subs.filter(s => s.isCorrect);
    const avgScoreCorrect = correctSubs.length > 0
      ? correctSubs.reduce((acc, s) => acc + s.studentAbilityScore, 0) / correctSubs.length
      : avgScoreTotal;

    const variance = subs.reduce((acc, s) => acc + Math.pow(s.studentAbilityScore - avgScoreTotal, 2), 0) / totalAttempts;
    const stdDev = Math.sqrt(variance) || 1.0;

    const rPbi = (stdDev > 0 && correctCount > 0 && correctCount < totalAttempts)
      ? ((avgScoreCorrect - avgScoreTotal) / stdDev) * Math.sqrt((p * (1 - p)))
      : 0.45;

    const cleanRPbi = Math.round(Math.max(-1.0, Math.min(1.0, rPbi)) * 100) / 100;

    // Parâmetro a (Discriminação): proporcional à correlação bisserial
    let paramA = Math.round((Math.max(0.1, cleanRPbi * 2.2)) * 100) / 100;
    if (cleanRPbi <= 0) paramA = 0.05;

    // Parâmetro c (Adivinhação baseada em taxa de acerto de alunos de baixa proficiência)
    const lowAbilitySubs = subs.filter(s => s.studentAbilityScore < 40);
    const lowAbilityCorrect = lowAbilitySubs.filter(s => s.isCorrect).length;
    const paramC = lowAbilitySubs.length > 0
      ? Math.round((lowAbilityCorrect / lowAbilitySubs.length) * 100) / 100
      : 0.20;

    // Determinar Status de Qualidade Psicométrica
    let status: "EXCELENTE" | "ADEQUADO" | "REQUER_REVISAO" | "ITEM_DEFEITUOSO_AMBIGUO" = "ADEQUADO";
    let recommendation = "Item calibrado e pronto para montagem de provas balanceadas.";

    if (cleanRPbi < 0.15 || paramA < 0.3) {
      status = "ITEM_DEFEITUOSO_AMBIGUO";
      recommendation = "Alerta Crítico: Item com discriminação nula ou negativa. Alunos de alta proficiência estão errando mais que os de baixa proficiência (provável ambiguidade de enunciado ou gabarito invertido).";
    } else if (cleanRPbi < 0.30 || successRate < 15 || successRate > 92) {
      status = "REQUER_REVISAO";
      recommendation = successRate < 15
        ? "Item excessivamente difícil. Avaliar se os pré-requisitos foram cobertos em aula."
        : successRate > 92
        ? "Item com baixíssimo poder discriminatório (quase todos acertam). Sugere-se enriquecer com casos de borda."
        : "Item com correlação limítrofe. Recomenda-se ajustar distratores.";
    } else if (paramA >= 1.2 && cleanRPbi >= 0.40) {
      status = "EXCELENTE";
      recommendation = "Item de altíssima precisão psicométrica. Excelente para diferenciar alunos adequados de avançados no SAEP.";
    }

    return {
      itemId: params.itemId,
      itemTitle: params.itemTitle,
      difficultyParamB: paramB,
      discriminationParamA: paramA,
      guessingParamC: paramC,
      successRatePercentage: Math.round(successRate * 10) / 10,
      pointBiserialCorrelation: cleanRPbi,
      totalAttempts,
      qualityStatus: status,
      diagnosticRecommendation: recommendation
    };
  }

