  // 5. SMART EXAM ASSEMBLER (4 BOOKLETS A, B, C, D WITH ROTATION)
  // =========================================================================
  static assembleBalancedExam(params: {
    examTitle: string;
    courseName: string;
    classId: string;
    durationMinutes?: number;
    distribution: { easyPct: number; mediumPct: number; hardPct: number };
    availableBankItems: Array<{
      id: string;
      title: string;
      type: string;
      difficulty: "Fácil" | "Médio" | "Difícil";
      statement: string;
      options?: Array<{ letter: string; text: string }>;
      correctAnswer: string;
      points?: number;
    }>;
  }): AssembledExamBooklet[] {
    const items = [...params.availableBankItems];
    const duration = params.durationMinutes || 90;
    const versions: Array<"A" | "B" | "C" | "D"> = ["A", "B", "C", "D"];

    // Embaralhamento determinístico por versão
    return versions.map((versionLetter, vIdx) => {
      // Cria uma cópia com rotação/embaralhamento baseado no índice da versão
      const rotatedItems = [...items].sort((a, b) => {
        const hashA = (a.id + versionLetter).split("").reduce((acc, c) => acc + c.charCodeAt(0), 0);
        const hashB = (b.id + versionLetter).split("").reduce((acc, c) => acc + c.charCodeAt(0), 0);
        return hashA - hashB;
      });

      const assembledItems: AssembledExamItem[] = rotatedItems.map((it, idx) => {
        let rotatedOptions = it.options ? [...it.options] : undefined;
        let newCorrectAnswer = it.correctAnswer;

        // Para múltipla escolha, rotaciona as alternativas também
        if (rotatedOptions && rotatedOptions.length > 0) {
          const opts = rotatedOptions;
          const correctOpt = opts.find(o => o.letter === it.correctAnswer || o.text === it.correctAnswer);
          const letters = ["A", "B", "C", "D", "E"].slice(0, opts.length);
          
          // Permuta alternativas conforme a versão
          const shift = (vIdx + idx) % opts.length;
          const permuted = opts.map((_, i) => opts[(i + shift) % opts.length]);
          
          rotatedOptions = permuted.map((opt, i) => ({
            letter: letters[i],
            text: opt.text
          }));

          if (correctOpt) {
            const foundIndex = permuted.findIndex(p => p.text === correctOpt.text);
            newCorrectAnswer = foundIndex !== -1 ? letters[foundIndex] : "A";
          }
        }

        return {
          itemNumber: idx + 1,
          originalId: it.id,
          title: it.title,
          type: it.type,
          difficulty: it.difficulty,
          statement: it.statement,
          options: rotatedOptions,
          correctAnswer: newCorrectAnswer,
          points: it.points || Math.round(100 / Math.max(1, rotatedItems.length))
        };
      });

      const answerKey = assembledItems.map(it => ({
        itemNumber: it.itemNumber,
        correctOptionOrSummary: it.options ? it.correctAnswer : it.correctAnswer.substring(0, 40),
        points: it.points
      }));

      const totalPoints = assembledItems.reduce((acc, it) => acc + it.points, 0);

      return {
        versionLetter,
        examTitle: params.examTitle,
        courseName: params.courseName,
        classId: params.classId,
        durationMinutes: duration,
        totalPoints,
        items: assembledItems,
        answerKeyMatrix: answerKey
      };
    });
  }

