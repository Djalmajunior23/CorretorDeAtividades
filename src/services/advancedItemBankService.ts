  // =========================================================================
  // 3. PARAMETRIC POLIMORPHIC GENERATOR (ANTI-CHEAT ENGINE)
  // =========================================================================
  static generateParametricInstances(params: {
    title: string;
    scenarioTemplate: string;
    studentList: Array<{ id: string; name: string }>;
    formulaType: "FINANCE_INTEREST" | "SHIPPING_WEIGHT" | "ARRAY_ANOMALY" | "SQL_DISCOUNT";
  }): ParametricQuestionTemplate {
    const templateId = `param_tmpl_${Date.now()}_${Math.random().toString(36).substring(2, 6)}`;
    const instances: ParametricSeedInstance[] = [];

    params.studentList.forEach((st, idx) => {
      // Gera semente pseudo-aleatória determinística baseada no ID do estudante
      const seedVal = Math.abs(st.id.split("").reduce((acc, c) => acc + c.charCodeAt(0), 0) + (idx * 37)) % 1000;
      
      let renderedStatement = "";
      let expectedResult: string | number = "";
      let testCases: Array<{ input: string; expectedOutput: string; isHidden: boolean }> = [];
      const parameters: Record<string, string | number> = {};

      if (params.formulaType === "FINANCE_INTEREST") {
        const capital = 1000 + (seedVal % 15) * 500;
        const taxa = 2 + (seedVal % 7);
        const meses = 3 + (seedVal % 10);
        const total = Math.round((capital * Math.pow(1 + taxa / 100, meses)) * 100) / 100;

        parameters.capital = capital;
        parameters.taxa = taxa;
        parameters.meses = meses;

        renderedStatement = `Uma fintech contratou você para calcular o montante de um investimento inicial de R$ ${capital},00 com taxa composta de ${taxa}% ao mês durante ${meses} meses. Escreva a função calcularMontante(c, i, t) que retorne o valor final arredondado em 2 casas decimais.`;
        expectedResult = total;

        testCases = [
          { input: `[${capital}, ${taxa}, ${meses}]`, expectedOutput: `${total}`, isHidden: false },
          { input: `[${capital}, ${taxa}, 0]`, expectedOutput: `${capital}.00`, isHidden: false },
          { input: `[${capital * 2}, ${taxa}, ${meses}]`, expectedOutput: `${(total * 2).toFixed(2)}`, isHidden: true }
        ];
      } else if (params.formulaType === "SHIPPING_WEIGHT") {
        const pesoBase = 5 + (seedVal % 20);
        const tarifaKg = 12 + (seedVal % 8);
        const taxaUrgente = 25 + (seedVal % 15);
        const custoPadrao = (pesoBase * tarifaKg);
        const custoUrgente = custoPadrao + taxaUrgente;

        parameters.peso = pesoBase;
        parameters.tarifaKg = tarifaKg;
        parameters.taxaUrgente = taxaUrgente;

        renderedStatement = `Para um operador logístico, calcule o frete de uma carga de ${pesoBase}kg com tarifa de R$ ${tarifaKg}/kg e taxa de entrega expressa de R$ ${taxaUrgente}. Retorne um objeto com { padrao: ${custoPadrao}, expressa: ${custoUrgente} }.`;
        expectedResult = JSON.stringify({ padrao: custoPadrao, expressa: custoUrgente });

        testCases = [
          { input: `[${pesoBase}, ${tarifaKg}, ${taxaUrgente}]`, expectedOutput: JSON.stringify({ padrao: custoPadrao, expressa: custoUrgente }), isHidden: false },
          { input: `[0, ${tarifaKg}, ${taxaUrgente}]`, expectedOutput: JSON.stringify({ padrao: 0, expressa: taxaUrgente }), isHidden: true }
        ];
      } else {
        const threshold = 50 + (seedVal % 40);
        parameters.threshold = threshold;

        renderedStatement = `Crie uma função filtrarSensores(leituras, limite = ${threshold}) que receba um array de telemetria e retorne apenas os valores estritamente maiores que ${threshold}, ordenados de forma decrescente.`;
        expectedResult = `[${threshold + 10}, ${threshold + 5}]`;

        testCases = [
          { input: `[[${threshold - 5}, ${threshold + 5}, ${threshold + 10}], ${threshold}]`, expectedOutput: `[${threshold + 10}, ${threshold + 5}]`, isHidden: false },
          { input: `[[], ${threshold}]`, expectedOutput: `[]`, isHidden: true }
        ];
      }

      const verificationHash = `vhash_${Math.random().toString(36).substring(2, 8)}_${seedVal}`;

      instances.push({
        seedId: `seed_${st.id}`,
        studentNameOrId: st.name || st.id,
        parameters,
        renderedStatement,
        expectedResult,
        testCases,
        verificationHash
      });
    });

    return {
      templateId,
      title: params.title || "Questão Parametrizada Anti-Cola",
      baseScenario: params.scenarioTemplate || "Template dinâmico com semente exclusiva por aluno.",
      variableDefinitions: [
        { name: "var1", type: "number", rangeOrValues: "10-100" },
        { name: "var2", type: "number", rangeOrValues: "2-15" }
      ],
      formulaOrLogicDescription: "Geração polimórfica de casos de teste com determinismo por hash de matrícula.",
      sampleInstances: instances,
      createdAt: new Date().toISOString()
    };
  }

